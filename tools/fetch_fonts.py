"""
Download the two typefaces and write a local @font-face stylesheet.

Run once, then commit the .woff2 files. After that the site has no font
dependency on any outside service, which is the point: the error pages and the
offline page must look right with no network at all, and a CDN request on every
page load is a request that can hang.

    python tools/fetch_fonts.py

Both families are licensed under the SIL Open Font License, which permits
self-hosting and redistribution. The licence text is saved alongside the files.
"""

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "core" / "static" / "core" / "fonts"

# The Google Fonts CSS endpoint only returns woff2 to a browser-like client.
# A generic Chrome UA; no identifying information is sent.
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36"
)

# Display serif: Cormorant Garamond. Text grotesque: Inter Tight.
CSS_URL = (
    "https://fonts.googleapis.com/css2"
    "?family=Cormorant+Garamond:wght@300;400;600"
    "&family=Inter+Tight:wght@400;500;600"
    "&display=swap"
)

# Only the Latin ranges. Skipping Cyrillic and Vietnamese keeps the payload
# small, and nothing on the site needs them.
WANTED_SUBSETS = {"latin", "latin-ext"}


def fetch(url: str, binary: bool = False):
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=30) as response:
        data = response.read()
    return data if binary else data.decode("utf-8")


def parse_blocks(css: str) -> list[dict]:
    """
    Pull one record per @font-face rule out of the Google Fonts CSS.

    Each rule is preceded by a comment naming its subset, which is how we tell
    the latin ranges from the rest.
    """
    blocks = []
    subset = "unknown"
    for chunk in re.split(r"(/\*[^*]*\*/)", css):
        comment = re.fullmatch(r"/\*\s*([a-z0-9\-\[\]]+)\s*\*/", chunk.strip())
        if comment:
            subset = comment.group(1)
            continue
        for rule in re.findall(r"@font-face\s*\{([^}]*)\}", chunk):
            family = re.search(r"font-family:\s*'([^']+)'", rule)
            weight = re.search(r"font-weight:\s*(\d+)", rule)
            style = re.search(r"font-style:\s*(\w+)", rule)
            url = re.search(r"url\((https://[^)]+\.woff2)\)", rule)
            unicode_range = re.search(r"unicode-range:\s*([^;]+);", rule)
            if not (family and url):
                continue
            blocks.append(
                {
                    "subset": subset,
                    "family": family.group(1),
                    "weight": weight.group(1) if weight else "400",
                    "style": style.group(1) if style else "normal",
                    "url": url.group(1),
                    "unicode_range": (
                        unicode_range.group(1).strip() if unicode_range else ""
                    ),
                }
            )
    return blocks


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def main() -> int:
    FONT_DIR.mkdir(parents=True, exist_ok=True)

    print(f"Reading font list from Google Fonts")
    try:
        css = fetch(CSS_URL)
    except Exception as exc:  # noqa: BLE001
        print(f"FAILED to reach Google Fonts: {type(exc).__name__}: {exc}")
        print("The site falls back to system fonts, which is handled in site.css.")
        return 1

    blocks = [b for b in parse_blocks(css) if b["subset"] in WANTED_SUBSETS]
    if not blocks:
        print("FAILED: no latin woff2 rules found in the response.")
        return 1

    lines = [
        "/*",
        " * Self-hosted webfonts. Generated by tools/fetch_fonts.py.",
        " * Cormorant Garamond and Inter Tight, SIL Open Font License 1.1.",
        " * Do not edit by hand: re-run the script instead.",
        " */",
        "",
    ]

    written = 0
    for block in blocks:
        name = (
            f"{slugify(block['family'])}-{block['weight']}"
            f"-{block['subset']}.woff2"
        )
        target = FONT_DIR / name
        if not target.exists():
            try:
                target.write_bytes(fetch(block["url"], binary=True))
            except Exception as exc:  # noqa: BLE001
                print(f"  skipped {name}: {type(exc).__name__}: {exc}")
                continue
        written += 1
        size_kb = target.stat().st_size / 1024
        print(f"  {name}  {size_kb:.0f} kB")

        lines += [
            "@font-face {",
            f"  font-family: '{block['family']}';",
            f"  font-style: {block['style']};",
            f"  font-weight: {block['weight']};",
            # swap: text is visible immediately in the fallback face and is
            # replaced when the webfont arrives. Never invisible text.
            "  font-display: swap;",
            f"  src: url('fonts/{name}') format('woff2');",
        ]
        if block["unicode_range"]:
            lines.append(f"  unicode-range: {block['unicode_range']};")
        lines += ["}", ""]

    (FONT_DIR.parent / "fonts.css").write_text("\n".join(lines), encoding="utf-8")
    print(f"\nWrote {written} files and core/static/core/fonts.css")
    return 0


if __name__ == "__main__":
    sys.exit(main())
